<script>
    document.addEventListener('DOMContentLoaded', () => {
        const buttons = document.querySelectorAll('.callback-button');
        const modalClip = document.querySelector('.modal-clip');
        const modalContent = document.querySelector('.modal-content');
        const backdrop = document.querySelector('.backdrop');
        const submitButton = document.querySelector('.submit-button');
        const closeButtons = document.querySelectorAll('[data-close-modal]');
        const form = document.querySelector('#callbackForm');

        const loadingSpinner = document.getElementById('loadingSpinner');
        const successMessage = document.getElementById('successMessage');
        const errorMessage = document.getElementById('errorMessage');

        function showMessage(element, message) {
            element.textContent = message;
            element.style.display = 'block';
            setTimeout(() => {
                element.style.display = 'none';
            }, 5000);
        }

        function resetMessages() {
            successMessage.style.display = 'none';
            errorMessage.style.display = 'none';
            loadingSpinner.style.display = 'none';
        }

        async function submitForm(formData) {
            try {
                const response = await fetch('/api/callback.php', {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                    },
                    body: JSON.stringify(Object.fromEntries(formData))
                });

                const data = await response.json();

                if (data.status === 'success') {
                    showMessage(successMessage, data.message);
                    // form.reset();
                    // setTimeout(closeModal, 3000); // Close modal after 3 seconds
                } else {
                    showMessage(errorMessage, data.message || 'Something went wrong. Please try again.');
                }
            } catch (error) {
                showMessage(errorMessage, 'Network error. Please try again later.');
            } finally {
                submitButton.disabled = false;
                loadingSpinner.style.display = 'none';
            }
        }

        form.addEventListener('submit', async (e) => {
            e.preventDefault();
            resetMessages();

            // Validate form
            const formData = new FormData(form);
            const name = formData.get('name').trim();
            const phone = formData.get('phone').trim();
            const preferredTime = formData.get('preferred_time').trim();

            if (!name || !phone || !preferredTime) {
                showMessage(errorMessage, 'Please fill in all fields.');
                return;
            }

            // Show loading state
            submitButton.disabled = true;
            loadingSpinner.style.display = 'block';

            // Submit form
            await submitForm(formData);
        });

        let activeButton = null;
        let isModalOpen = false;

        function openModal(button) {
            if (isModalOpen) return;

            const buttonRect = button.getBoundingClientRect();
            const centerX = buttonRect.left + buttonRect.width / 2;
            const centerY = buttonRect.top + buttonRect.height / 2;

            activeButton = button;
            isModalOpen = true;

            modalClip.style.top = centerY + 'px';
            modalClip.style.left = centerX + 'px';
            modalContent.style.visibility = 'visible';

            requestAnimationFrame(() => {
                backdrop.classList.add('visible');
                buttons.forEach(btn => btn.classList.add('hiddenopacity'));
                modalClip.classList.add('expanded');

                setTimeout(() => {
                    modalContent.classList.add('visible');
                    submitButton.classList.add('visible');
                }, 300);
            });
        }

        function closeModal() {
            if (!isModalOpen || !activeButton) return;

            const buttonRect = activeButton.getBoundingClientRect();

            isModalOpen = false;
            modalContent.classList.remove('visible');
            submitButton.classList.remove('visible');
            backdrop.classList.remove('visible');

            modalClip.style.top = (buttonRect.top + buttonRect.height / 2) + 'px';
            modalClip.style.left = (buttonRect.left + buttonRect.width / 2) + 'px';
            modalClip.classList.remove('expanded');

            buttons.forEach(btn => btn.classList.remove('hiddenopacity'));

            setTimeout(() => {
                modalContent.style.visibility = 'hidden';
                activeButton = null;
            }, 500);
        }

        // Event Listeners
        buttons.forEach(button => {
            button.addEventListener('click', () => openModal(button));
        });

        closeButtons.forEach(button => {
            button.addEventListener('click', (e) => {
                e.stopPropagation();
                closeModal();
            });
        });


        // Prevent closing when clicking inside the modal
        modalContent.addEventListener('click', (e) => {
            e.stopPropagation();
        });
    });
</script>
